"""Общие regex-паттерны для стратегий (устранение дублей между S4r/S5)."""

from __future__ import annotations

import re

# Multi-fact запросы: комбинация врач + цена, стаж + стоимость и т.д.
MULTI_FACT_RE = re.compile(
    r"(и\s+скольк|и\s+цен|и\s+стои|скольк.*врач|врач.*скольк|врач.*цен|"
    r"цен.*врач|стоматолог.*приём|приём.*стоматолог|опыт.*цен|цен.*опыт|"
    r"врач.*приём|приём.*врач)",
    re.IGNORECASE,
)
