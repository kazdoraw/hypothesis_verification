def _generate_variation(l2: str) -> Optional[str]:
    """Generate a random variation for an L2 class."""
    if l2 not in VARIATION_TEMPLATES:
        return None
    
    template = random.choice(VARIATION_TEMPLATES[l2])
    
    try:
        text = template.format(
            specialist=random.choice(SPECIALISTS),
            day=random.choice(DAYS),
            procedure=random.choice(PROCEDURES),
            location=random.choice(LOCATIONS),
            duration=random.choice(DURATIONS),
            symptom=random.choice(SYMPTOMS),
            pain_type=random.choice(PAIN_TYPES),
            problem=random.choice(PROBLEMS),
            doctor=random.choice(DOCTORS),
            equipment=random.choice(EQUIPMENT),
            payment=random.choice(PAYMENT_METHODS),
            reason=random.choice(CANCEL_REASONS),
            restriction=random.choice(RESTRICTIONS),
            time=random.choice(TIMES),
            intensity=random.choice(PAIN_TYPES),
        )
        return text
    except KeyError:
        return None


def _apply_text_augmentation(text: str, aug_type: str) -> str:
    """Apply augmentation to text."""
    if aug_type == "lowercase":
        return text.lower()
    elif aug_type == "uppercase":
        return text.upper()
    elif aug_type == "punctuation":
        text = text.rstrip("?!.")
        return text + random.choice(["", "?", "!", ".", "...", "!!", "?!"])
    elif aug_type == "prefix":
        prefixes = ["Здравствуйте, ", "Добрый день, ", "Привет, ", "Подскажите, ", "Скажите, ", ""]
        return random.choice(prefixes) + text[0].lower() + text[1:]
    elif aug_type == "suffix":
        suffixes = [" пожалуйста", " спасибо", " заранее спасибо", ""]
        return text.rstrip("?!.") + random.choice(suffixes)
    elif aug_type == "typo":
        # Simple typo simulation
        if len(text) > 5:
            idx = random.randint(2, len(text) - 3)
            chars = list(text)
            if random.random() < 0.5 and chars[idx].isalpha():
                chars[idx] = chars[idx].lower() if chars[idx].isupper() else chars[idx].upper()
            else:
                chars[idx], chars[idx+1] = chars[idx+1], chars[idx]
            return "".join(chars)
        return text
    elif aug_type == "emoji":
        emojis = ["", "", "", " 🦷", " 😊", " 👍", " 🙏", " 😢"]
        return text.rstrip("?!.") + random.choice(emojis)
    return text


def generate_d1_dataset_v2(
    n: int = 10000,
    seed: int = 42,
    include_augmentation: bool = True,
) -> pd.DataFrame:
    """
    Generate D1 dataset with two-level classification.
    
    Args:
        n: Total number of samples to generate
        seed: Random seed
        include_augmentation: Whether to include augmented samples
        
    Returns:
        DataFrame with columns: id, text, label_l1, label_l2, scenario, source, complexity
    """
    random.seed(seed)
    
    # Calculate samples per L2 class
    n_l2_classes = len(INTENT_LABELS_L2)
    base_per_class = n // n_l2_classes
    extra = n % n_l2_classes
    
    data = []
    id_counter = 1
    used_texts = set()
    
    # Augmentation types for scaling
    aug_types = ["lowercase", "uppercase", "punctuation", "prefix", "suffix", "typo", "emoji"]
    
    for l2 in INTENT_LABELS_L2:
        l1 = L2_TO_L1[l2]
        scenario = L2_TO_SCENARIO[l2]
        templates = MESSAGE_TEMPLATES_L2.get(l2, [])
        
        # Calculate target count for this class
        target_count = base_per_class + (1 if extra > 0 else 0)
        extra -= 1 if extra > 0 else 0
        
        generated = 0
        attempts = 0
        max_attempts = target_count * 20  # More attempts for scaling
        
        # Phase 1: Original templates
        for template in templates:
            if generated >= target_count:
                break
            text_normalized = template.lower().strip()
            if text_normalized not in used_texts:
                used_texts.add(text_normalized)
                data.append({
                    "id": id_counter,
                    "text": template,
                    "label_l1": l1,
                    "label_l2": l2,
                    "scenario": scenario,
                    "source": "template",
                    "complexity": "simple" if len(template.split()) <= 5 else "medium",
                })
                id_counter += 1
                generated += 1
        
        # Phase 2: Parametric variations
        while generated < target_count * 0.6 and attempts < max_attempts and l2 in VARIATION_TEMPLATES:
            attempts += 1
            text = _generate_variation(l2)
            if text is None:
                continue
            
            text_normalized = text.lower().strip()
            if text_normalized in used_texts:
                continue
            used_texts.add(text_normalized)
            
            data.append({
                "id": id_counter,
                "text": text,
                "label_l1": l1,
                "label_l2": l2,
                "scenario": scenario,
                "source": "variation",
                "complexity": "medium" if len(text.split()) > 5 else "simple",
            })
            id_counter += 1
            generated += 1
        
        # Phase 3: Augmented versions (scaling to target)
        if include_augmentation:
            base_texts = [d["text"] for d in data if d["label_l2"] == l2]
            aug_attempts = 0
            max_aug_attempts = target_count * 10
            
            while generated < target_count and aug_attempts < max_aug_attempts:
                aug_attempts += 1
                
                if not base_texts:
                    break
                
                base_text = random.choice(base_texts)
                aug_type = random.choice(aug_types)
                
                # Apply 1-2 augmentations
                text = _apply_text_augmentation(base_text, aug_type)
                if random.random() < 0.3:
                    text = _apply_text_augmentation(text, random.choice(aug_types))
                
                text_normalized = text.lower().strip()
                if text_normalized in used_texts:
                    continue
                used_texts.add(text_normalized)
                
                # Determine complexity
                complexity = "simple"
                if len(text.split()) > 5:
                    complexity = "medium"
                if len(text.split()) > 10 or "," in text:
                    complexity = "complex"
                
                data.append({
                    "id": id_counter,
                    "text": text,
                    "label_l1": l1,
                    "label_l2": l2,
                    "scenario": scenario,
                    "source": "augmented",
                    "complexity": complexity,
                })
                id_counter += 1
                generated += 1
        
        # Phase 4: Composite templates (greeting + intent)
        if generated < target_count and l2 not in ["greeting", "gratitude", "farewell", "confirmation", "unclear"]:
            greetings = ["Здравствуйте, ", "Добрый день! ", "Привет, ", ""]
            base_templates = MESSAGE_TEMPLATES_L2.get(l2, [])
            
            for greeting in greetings:
                for template in base_templates[:5]:  # Limit to avoid explosion
                    if generated >= target_count:
                        break
                    
                    if greeting:
                        text = greeting + template[0].lower() + template[1:]
                    else:
                        continue
                    
                    text_normalized = text.lower().strip()
                    if text_normalized in used_texts:
                        continue
                    used_texts.add(text_normalized)
                    
                    data.append({
                        "id": id_counter,
                        "text": text,
                        "label_l1": l1,
                        "label_l2": l2,
                        "scenario": scenario,
                        "source": "composite",
                        "complexity": "complex",
                    })
                    id_counter += 1
                    generated += 1
    
    # Shuffle
    random.shuffle(data)
    
    # Re-assign IDs
    for i, row in enumerate(data):
        row["id"] = i + 1
    
    return pd.DataFrame(data)


def generate_stratified_split(
    df: pd.DataFrame,
    train_ratio: float = 0.70,
    val_ratio: float = 0.15,
    test_ratio: float = 0.15,
    seed: int = 42,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Create stratified train/val/test split.
    
    Args:
        df: Full dataset
        train_ratio: Training set ratio
        val_ratio: Validation set ratio
        test_ratio: Test set ratio
        seed: Random seed
        
    Returns:
        Tuple of (train_df, val_df, test_df)
    """
    from sklearn.model_selection import train_test_split
    
    # First split: train+val vs test
    train_val, test = train_test_split(
        df,
        test_size=test_ratio,
        stratify=df["label_l2"],
        random_state=seed,
    )
    
    # Second split: train vs val
    val_size = val_ratio / (train_ratio + val_ratio)
    train, val = train_test_split(
        train_val,
        test_size=val_size,
        stratify=train_val["label_l2"],
        random_state=seed,
    )
    
    return train, val, test


def save_dataset(
    df: pd.DataFrame,
    output_dir: Path,
    name: str = "d1_messages_v4",
    create_splits: bool = True,
) -> Dict[str, Path]:
    """
    Save dataset to files.
    
    Args:
        df: Dataset DataFrame
        output_dir: Output directory
        name: Base name for files
        create_splits: Whether to create train/val/test splits
        
    Returns:
        Dict of file paths
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    
    paths = {}
    
    # Save full dataset
    full_path = output_dir / f"{name}_full.csv"
    df.to_csv(full_path, index=False)
    paths["full"] = full_path
    
    if create_splits:
        train, val, test = generate_stratified_split(df)
        
        train_path = output_dir / f"{name}_train.csv"
        val_path = output_dir / f"{name}_val.csv"
        test_path = output_dir / f"{name}_test.csv"
        
        train.to_csv(train_path, index=False)
        val.to_csv(val_path, index=False)
        test.to_csv(test_path, index=False)
        
        paths["train"] = train_path
        paths["val"] = val_path
        paths["test"] = test_path
    
    # Save metadata
    metadata = {
        "total_samples": len(df),
        "l1_distribution": df["label_l1"].value_counts().to_dict(),
        "l2_distribution": df["label_l2"].value_counts().to_dict(),
        "source_distribution": df["source"].value_counts().to_dict(),
        "complexity_distribution": df["complexity"].value_counts().to_dict(),
    }
    
    metadata_path = output_dir / f"{name}_metadata.json"
    with open(metadata_path, "w", encoding="utf-8") as f:
        json.dump(metadata, f, ensure_ascii=False, indent=2)
    paths["metadata"] = metadata_path
    
    return paths


